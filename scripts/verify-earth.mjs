import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

const { chromium } = createRequire(path.resolve(process.argv[2]))('playwright');
const browser = await chromium.launch({ channel:'chrome',headless:true });
await fs.mkdir('artifacts/earth',{recursive:true});
try {
  const page = await browser.newPage({viewport:{width:1000,height:760},reducedMotion:'reduce'});
  const errors=[];
  page.on('pageerror',error => errors.push(error.message));
  page.on('console',message => { if (message.type()==='error') errors.push(message.text()); });
  const started=Date.now();
  await page.goto(`${process.argv[3] || 'http://127.0.0.1:3000'}/works/laboratory/Earth`);
  await page.waitForFunction(() => document.querySelector('canvas')?.dataset.frames || document.querySelector('main [role="alert"]'),null,{timeout:60000});
  assert.equal(await page.locator('main [role="alert"]').count(),0,await page.locator('main [role="alert"]').allTextContents());
  const canvas=page.locator('canvas');
  const shot = async (options = {}) => {
    await page.locator('aside').evaluateAll(elements => elements.forEach(element => { element.style.visibility='hidden'; }));
    const image = await canvas.screenshot(options);
    await page.locator('aside').evaluateAll(elements => elements.forEach(element => { element.style.visibility=''; }));
    return image;
  };
  console.log('Earth initialization ms:',Date.now()-started);
  const originalOrbit=await shot({path:'artifacts/earth/orbit.png'});
  const firstFrames=await canvas.getAttribute('data-frames');
  await page.waitForTimeout(700);
  assert.equal(await canvas.getAttribute('data-frames'),firstFrames,'Paused Earth keeps rendering');
  await page.getByRole('button',{name:/CONTROLS/}).click();
  await page.getByRole('slider',{name:'Rayleigh scattering',exact:true}).fill('2');
  await page.waitForFunction(() => document.querySelector('canvas')?.dataset.atmosphere === '2,1',null,{timeout:90000});
  const moreRayleigh=await shot({path:'artifacts/earth/rayleigh-2.png'});
  await page.getByRole('slider',{name:'Mie scattering',exact:true}).fill('2');
  await page.waitForFunction(() => document.querySelector('canvas')?.dataset.atmosphere === '2,2',null,{timeout:90000});
  const moreMie=await shot({path:'artifacts/earth/mie-2.png'});
  assert.notEqual(moreMie.toString('base64'),moreRayleigh.toString('base64'),'Mie coefficient did not change rendered pixels');
  await page.getByRole('button',{name:'Cloudscape',exact:true}).click();
  await page.waitForTimeout(500);
  await shot({path:'artifacts/earth/edited-cloudscape.png'});
  await page.getByRole('button',{name:'Orbit',exact:true}).click();
  await page.getByRole('slider',{name:'Rayleigh scattering',exact:true}).fill('1');
  await page.getByRole('slider',{name:'Mie scattering',exact:true}).fill('1');
  await page.waitForFunction(() => document.querySelector('canvas')?.dataset.atmosphere === '1,1');
  await page.waitForTimeout(150);
  assert.equal((await shot()).toString('base64'),originalOrbit.toString('base64'),'Reset coefficients did not restore the default image');
  await page.getByRole('slider',{name:'Cloud coverage',exact:true}).fill('0');
  await page.waitForTimeout(300);
  await shot({path:'artifacts/earth/orbit-clear.png'});
  await page.getByRole('slider',{name:'Cloud coverage',exact:true}).fill('0.62');
  await page.getByRole('button',{name:'Cloudscape',exact:true}).click();
  await page.waitForTimeout(800);
  await shot({path:'artifacts/earth/cloudscape.png'});
  const clouds=await shot();
  await page.getByRole('slider',{name:'Cloud coverage',exact:true}).fill('0');
  await page.waitForTimeout(500);
  assert.notEqual((await shot()).toString('base64'),clouds.toString('base64'),'Cloud toggle did not change rendered pixels');
  await shot({path:'artifacts/earth/clear.png'});
  await page.getByRole('slider',{name:'Cloud coverage',exact:true}).fill('0.62');
  await page.getByRole('button',{name:'Sunset',exact:true}).click();
  await page.waitForTimeout(800);
  await shot({path:'artifacts/earth/sunset.png'});
  await page.getByRole('button',{name:'Play',exact:true}).click();
  const beforePlay=Number(await canvas.getAttribute('data-frames'));
  await page.waitForFunction(before => Number(document.querySelector('canvas')?.dataset.frames)>before+2,beforePlay,{timeout:30000});
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  await page.getByRole('button',{name:'Orbit',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(700);
  await page.screenshot({path:'artifacts/earth/mobile-controls.png'});
  await page.getByRole('button',{name:/CONTROLS/}).click();
  await page.screenshot({path:'artifacts/earth/mobile.png'});
  assert.deepEqual(errors,[]);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth>innerWidth),false);
  console.log('Earth: presets, cloud toggle, pause/play, mobile, and browser errors verified.');
} finally { await browser.close(); }
